// Lumevina Skin School motion studio: the music bed laid under the lesson clips.
//
//   node docs/school/motion/add-music.mjs [--only 1-1,6-2]     (from lumevina/; needs ffmpeg)
//
// For every lesson in docs/school/videos.js it puts music/bed.m4a (music.mjs) under
//   img/school/video/<id>.mp4 + <id>.webm          (AAC 128k in the MP4, Opus 96k in the WebM)
//   marketing/ads/out/video/<id>-9x16.mp4          (when the 9:16 cut exists)
// and writes the new sizes back into videos.js. The picture is copied as it is, never
// re-encoded, and only the clip's video stream is kept from the input, so running it again
// replaces the music rather than stacking it. The bed fades in over 0.8 s and out over the
// last 1.5 s, and each lesson starts at one of three places in the loop (chord changes are
// 8 s apart), by its number, so lessons watched back to back don't open on the same chord.
// The page's hero isn't a lesson: it plays muted on a loop and stays silent.
// render.mjs calls addMusic() on every lesson it renders, so a new clip comes out with it.
import fs from "node:fs";
import path from "node:path";
import { spawnSync } from "node:child_process";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "../../..");
export const BED = path.join(here, "music", "bed.m4a");
const BED_LEN = 48, FADE_IN = 0.8, FADE_OUT = 1.5;

const run = (args) => {
  const r = spawnSync("ffmpeg", ["-y", "-hide_banner", "-loglevel", "error", ...args], { stdio: ["ignore", "inherit", "inherit"] });
  if (r.status !== 0) throw new Error(`ffmpeg failed on ${args[args.length - 1]}`);
};
const duration = (file) => Number(spawnSync("ffprobe", ["-v", "error", "-select_streams", "v:0", "-show_entries", "format=duration", "-of", "csv=p=0", file], { encoding: "utf8" }).stdout.trim());
// where in the loop a lesson starts: 0, 8 or 16 s, by module + lesson number, never so late the clip runs past the end
export const offsetFor = (id, dur) => {
  const [m, l] = String(id).split("-").map(Number);
  const at = (((m || 0) + (l || 0)) % 3) * 8;
  return Math.max(0, Math.min(at, BED_LEN - dur - 0.5));
};

// lay the bed under one clip, in place
export function addMusic(file, id) {
  if (!fs.existsSync(BED)) throw new Error("no music bed: run node docs/school/motion/music.mjs first");
  const dur = duration(file);
  if (!(dur > 0)) throw new Error(`can't read the length of ${file}`);
  const webm = file.endsWith(".webm");
  const tmp = file.replace(/(\.\w+)$/, ".music$1");
  run(["-i", file, "-ss", String(offsetFor(id, dur)), "-i", BED, "-map", "0:v:0", "-map", "1:a:0", "-c:v", "copy",
    "-af", `atrim=0:${dur},asetpts=PTS-STARTPTS,afade=t=in:st=0:d=${FADE_IN},afade=t=out:st=${Math.max(0, dur - FADE_OUT)}:d=${FADE_OUT}`,
    ...(webm ? ["-c:a", "libopus", "-b:a", "96k"] : ["-c:a", "aac", "-b:a", "128k", "-movflags", "+faststart"]),
    "-t", String(dur), tmp]);
  fs.renameSync(tmp, file);
  return fs.statSync(file).size;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const i = process.argv.indexOf("--only"), only = i > 0 ? process.argv[i + 1].split(",") : null;
  const videosFile = path.join(root, "docs/school/videos.js");
  const w = {}; new Function("window", fs.readFileSync(videosFile, "utf8"))(w);
  const videos = w.SCHOOL_VIDEOS || {};
  for (const id of Object.keys(videos)) {
    if (only && !only.includes(id)) continue;
    const base = path.join(root, "img/school/video", id), reel = path.join(root, "marketing/ads/out/video", `${id}-9x16.mp4`);
    videos[id].bytes = addMusic(base + ".mp4", id);
    if (fs.existsSync(base + ".webm")) addMusic(base + ".webm", id);
    if (fs.existsSync(reel)) addMusic(reel, id);
    console.log(`${id}: music under the clip${fs.existsSync(reel) ? " and the 9:16 cut" : ""}, from ${offsetFor(id, videos[id].dur)} s in the loop`);
  }
  fs.writeFileSync(videosFile, `/* GENERATED by docs/school/motion/render.mjs: the lessons with a rendered explainer in img/school/video/. Don't edit; render again. */\nwindow.SCHOOL_VIDEOS = ${JSON.stringify(videos)};\n`);
}
