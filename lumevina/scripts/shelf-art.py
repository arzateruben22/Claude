# The shop's shelf pictures: each product photo with its studio background taken away, so the
# product stands on the shelf (js/shop.js) instead of sitting in a gray square.
#
#   python3 -m venv .venv && .venv/bin/pip install "rembg[cpu]" pillow     (once; the model, 180 MB, downloads on first run)
#   .venv/bin/python scripts/shelf-art.py            (from lumevina/; only photos without a shelf picture yet)
#   .venv/bin/python scripts/shelf-art.py --all      (every photo again)
#
# img/products/<name>.webp  →  img/products/shelf/<name>.webp   (cut out, trimmed to the product, 760 px tall at most)
# and js/shelf-art.js: each photo's shelf picture and its size, so the shelf lays out before the pictures load.
# The original photos stay as they are: the product feeds (scripts/build-feed.mjs) and search use them.
import glob, json, os, sys
from PIL import Image

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src_dir, out_dir = os.path.join(root, "img/products"), os.path.join(root, "img/products/shelf")
os.makedirs(out_dir, exist_ok=True)
redo = "--all" in sys.argv
MAX = 760

session = None
def cut(im):
    global session
    from rembg import remove, new_session
    if session is None: session = new_session("isnet-general-use")
    return remove(im, session=session)

art = {}
for f in sorted(glob.glob(os.path.join(src_dir, "*.webp"))):
    name = os.path.basename(f)
    out = os.path.join(out_dir, name)
    if redo or not os.path.exists(out):
        im = cut(Image.open(f).convert("RGB")).convert("RGBA")
        # trim to the product: what the cut kept, ignoring the faintest edge haze
        box = im.getchannel("A").point(lambda a: 255 if a > 12 else 0).getbbox()
        if box: im = im.crop(box)
        im.thumbnail((MAX, MAX), Image.LANCZOS)
        im.save(out, "WEBP", quality=84, method=6)
        print("cut", name, im.size, os.path.getsize(out) // 1024, "KB")
    w, h = Image.open(out).size
    art["img/products/" + name] = ["img/products/shelf/" + name, w, h]

js = ("/* GENERATED by scripts/shelf-art.py: each product photo's shelf picture (cut out, trimmed) and its size.\n"
      "   Don't edit; add the photo to img/products/ and run the script. */\n"
      "window.LUMEVINA_SHELF_ART = {\n" +
      ",\n".join('  "%s": { src: "%s", w: %d, h: %d }' % (k, v[0], v[1], v[2]) for k, v in art.items()) +
      "\n};\n")
open(os.path.join(root, "js/shelf-art.js"), "w").write(js)
print(len(art), "shelf pictures → js/shelf-art.js")
