// Writes server/seed-products.sql: one products row per item in js/catalog.js.
// Safe to run again: existing rows keep their stock, price and hidden flag
// (Evelyn changes those in the dashboard); names, brands and types update.
//
//   node scripts/seed-products.mjs        (from lumevina/), then run the file in Supabase's SQL editor

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
globalThis.window = {};
await import(path.join(root, "js/catalog.js"));
const CAT = globalThis.window.LUMEVINA_CATALOG;
const q = (v) => (v == null ? "null" : "'" + String(v).replace(/'/g, "''") + "'");

const rows = CAT.products.map((p) => `  (${q(p.id)}, ${q(p.name)}, ${q(p.brand)}, ${q(p.cat)}, ${Math.round(Number(p.price) * 100)}, ${p.stock == null ? "null" : Math.max(0, Math.round(p.stock))}, ${p.draft ? "true" : "false"}, ${q(p.kind || "product")}, ${p.consult ? "true" : "false"})`);
const sql = `-- GENERATED by scripts/seed-products.mjs from js/catalog.js (${CAT.products.length} products). Run in Supabase's SQL editor.
insert into products (id, name, brand, category, price_cents, stock, hidden, kind, consult) values
${rows.join(",\n")}
on conflict (id) do update set name = excluded.name, brand = excluded.brand, category = excluded.category, updated_at = now();
`;
fs.writeFileSync(path.join(root, "server/seed-products.sql"), sql);
console.log(`wrote server/seed-products.sql (${CAT.products.length} products)`);
