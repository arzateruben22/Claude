"""Generate the eight part scripts (ep13..ep20) and their claims ledgers from lf01/script.md.

  python3 -I films/channels/physics/lf01/parts.py

A part is one chapter of the long film: its own 2 s hook line (the chapter's `part hook:`) in place of the chapter's bridge (the vo before `{|}`),
the chapter's lines, ending on the chapter's cliffhanger (its last line), then "Part N of 8. Full video on YouTube."
"""
import json
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
CH = HERE.parent
CHAPTERS = ["wings", "fly", "pop", "sound", "bullet", "leader", "light", "still"]
TITLES = ["Watch a wing, slowed ten times", "A fly's wings, then a splash", "A popcorn pop, in slow motion", "Watch sound cross a kitchen",
          "A bullet, through an apple, slowly", "Lightning, a million times slower", "Slow light until it crawls", "Slower than a snail: light"]
FIRST_EP = 13
src = (HERE / "script.md").read_text()
claims = {c["id"]: c for c in json.loads((HERE / "claims.json").read_text())}
beats = {}
for m in re.finditer(r"(?ms)^## (\w+) \{(.*?)\} \([\d.]+–[\d.]+ s\)\n(.*?)(?=^## |\Z)", src):
    beats[m.group(1)] = (m.group(2), m.group(3))
for n, ch in enumerate(CHAPTERS, 1):
    head, body = beats[ch]
    hook = re.search(r"part hook: (.*?) ·", head).group(1).strip()
    shot = re.search(r"shot: (.*?) · counter", head).group(1)
    vo = re.search(r"(?m)^vo: (.*)$", body).group(1)
    if "{|}" in vo:
        vo = vo.split("{|}", 1)[1].strip()
    ep = f"ep{FIRST_EP + n - 1}"
    d = CH / ep
    (d / "out").mkdir(parents=True, exist_ok=True)
    tags = sorted(set(re.findall(r"\{(c\d+)\}", vo)), key=lambda x: int(x[1:]))
    # the part's claim ledger: the claims its lines cite, with the sentence field left as the lf01 ledger has it
    ledger = [claims[t] for t in tags]
    (d / "claims.json").write_text(json.dumps(ledger, indent=0, ensure_ascii=False))
    text = f'''# Reality Rulebook · Season 3 · Part {n} of 8: "{TITLES[n - 1]}" (draft; a physicist signs off before it posts)

Folder {ep}: chapter {n} of the long film lf01 ("Slow Down One Second Until Light Stands Still"), rendered natively in 9:16 from the same kitchen scene.
Generated by lf01/parts.py from lf01/script.md. 9:16, 1:01 to 1:15 (never under 1:01), narrated by a synthetic voice (af_bella at speed 0.85, labeled as AI).
Hook line (2 s) in place of the long film's bridge; the chapter; its cliffhanger; then "Part {n} of 8. Full video on YouTube."
Shot: {shot}

## hook {{chapter: {n} · part hook · energy: 0.6 · pre: 0.1}} (0.0–3.0 s)
vo: {hook} {{-}}

## body {{chapter: {ch} · shot: {shot} · energy: 0.7 · pre: 0.15}} (3.0–60.0 s)
vo: {vo}

## tease {{end card held ≥ 1.5 s · signature: knocks D6, B5, G5 at 0, +12, +20 frames · energy: 0.4}} (60.0–66.0 s)
vo: Part {n} of 8. {{-}} Full video on YouTube. {{-}}
end card: "Part {n} of 8" · "Full video on YouTube" · footnote: "Reality Rulebook · Season 3"

## Notes
- Chapter title (the long film's description.md chapter list and this part's title must match exactly): "{TITLES[n - 1]}".
- Every claim is OPEN: a person must open the sources (claims.json; derivations carry no URL). TODO: the handle, a physicist's sign-off, the AI-voice label.
'''
    (d / "script.md").write_text(text)
    words = len(re.findall(r"[A-Za-z0-9'’-]+", re.sub(r"\{[^}]*\}", "", vo).replace("*", "")))
    print(ep, f"Part {n}: {TITLES[n-1]!r}: hook '{hook}', {words} words, claims {tags}")
