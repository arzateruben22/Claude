// Screenshot the in-game phone from the pause screen (home, then Credits).   node tools/phone-shot.mjs <outDir> [WxH]
import { chromium } from 'playwright';
import { mkdirSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
const ROOT = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const [dir, size = '1280x720'] = process.argv.slice(2), [W, H] = size.split('x').map(Number);
mkdirSync(path.resolve(dir), { recursive: true });
const browser = await chromium.launch({ args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const ctx = await browser.newContext({ viewport: { width: W, height: H }, ...(W < 600 ? { isMobile: true, hasTouch: true, deviceScaleFactor: 2 } : {}) });
await ctx.addInitScript(() => localStorage.setItem('tsu.settings', JSON.stringify({ quality: 'low', adaptive: false, density: 'light', driver: 'wrench' })));
const page = await ctx.newPage(); page.setDefaultTimeout(180000);
const errors = []; page.on('pageerror', (e) => errors.push(String(e)));
await page.goto(pathToFileURL(path.join(ROOT, 'dist', 'top-speed-ultra.html')).href);
await page.waitForFunction(() => window.__game?.net && document.querySelector('.overlay.menu'));
await page.getByRole('button', { name: 'Drive', exact: true }).click();
await page.waitForFunction(() => !window.__game.inAttract && !document.querySelector('.loadbar'));
await page.evaluate(() => window.__game.setPaused(true));
await page.getByRole('button', { name: 'Phone', exact: true }).click();
await page.waitForTimeout(600);
await page.screenshot({ path: path.join(dir, `phone-home-${W}.png`), timeout: 180000 });
await page.getByRole('button', { name: 'Credits', exact: true }).click();
await page.waitForTimeout(300);
await page.screenshot({ path: path.join(dir, `phone-credits-${W}.png`), timeout: 180000 });
await page.getByRole('button', { name: '‹ Apps' }).click();
await page.getByRole('button', { name: 'Map', exact: true }).click();
const map = await page.locator('.worldmap').count();
console.log(JSON.stringify({ dir, mapOpened: map === 1, errors }));
await browser.close();
