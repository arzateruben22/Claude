// Writes the server's own copy of the catalog for the Supabase Edge Functions, from the game's catalog:
//   npm run store:sync            write server/supabase/functions/_shared/catalog.json
//   npm run store:sync -- --check exit 1 if the copy is out of date (the regression suite runs this)
//
// The functions charge what this copy says and grant what it lists, never what the page sends. Each sku carries,
// from cosmetics.json: `grants_ready` (every grant is 'ready', so live Stripe keys may sell it) and
// `while_subscribed` (the grants a subscription takes back when it ends). Run it after any change to
// src/store/catalog.json or src/store/cosmetics.json, then redeploy both functions.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const catalog = JSON.parse(readFileSync(join(root, 'src/store/catalog.json'), 'utf8'));
const cosmetics = JSON.parse(readFileSync(join(root, 'src/store/cosmetics.json'), 'utf8'));
const ents = new Map(cosmetics.entitlements.map((e) => [e.id, e]));

const KEEP = ['sku', 'name', 'kind', 'price_cents', 'currency', 'mode', 'interval', 'window', 'custom_amount', 'grants', 'available'];
const skus = catalog.map((c) => {
  const o = {};
  for (const k of KEEP) if (k in c) o[k] = c[k];
  o.grants_ready = c.grants.every((g) => ents.get(g)?.status === 'ready');
  o.while_subscribed = c.grants.filter((g) => ents.get(g)?.while === 'subscribed');
  return o;
});
const out = JSON.stringify({ note: 'Generated by tools/store-sync-catalog.mjs from src/store/catalog.json and cosmetics.json. Do not edit by hand.', cosmetics_version: cosmetics.version, cosmetics_updated: cosmetics.updated, skus }, null, 2) + '\n';

const dest = join(root, 'server/supabase/functions/_shared/catalog.json');
if (process.argv.includes('--check')) {
  let now = '';
  try { now = readFileSync(dest, 'utf8'); } catch { /* missing */ }
  if (now !== out) { console.log('server catalog: out of date. Run `npm run store:sync` and redeploy the functions.'); process.exit(1); }
  console.log(`server catalog in sync: ${skus.length} skus, ${skus.filter((s) => s.available).length} available, ${skus.filter((s) => s.grants_ready).length} with every grant ready`);
} else {
  mkdirSync(dirname(dest), { recursive: true });
  writeFileSync(dest, out);
  console.log(`wrote ${dest}: ${skus.length} skus`);
}
